#!/usr/bin/env perl
# Print the versions.lock for oracle O3: perl -V summary, and the version of
# every module biber 2.22 loads (transitively), as resolved by this perl.
# Usage: vendor/perl/bin/perl tools/oracle/list-versions.pl <biber-src>
use strict;
use warnings;
use Config;

my $src = shift or die "usage: $0 <biber-src>\n";
unshift @INC, "$src/blib/lib";

print "# oracle O3 versions.lock -- generated by tools/oracle/list-versions.pl\n";
print "# perl: $^V ($Config{archname}) useithreads=",
  ($Config{useithreads} // 'undef'), " useshrplib=$Config{useshrplib}\n";
my $summary = `$^X -V`; my ($line) = $summary =~ /^(Summary of my perl5.*)$/m;
print "# $line\n" if $line;
my ($cto) = $summary =~ /Compile-time options:\s*(.*?)\n\s*(?:Built|Locally|\z)/s; if ($cto) { $cto =~ s/\s+/ /g; print "# Compile-time options: $cto\n" }
print "# ccflags: $Config{ccflags}\n";
print "# optimize: $Config{optimize}\n";
my $libxml = eval { require XML::LibXML; XML::LibXML::LIBXML_DOTTED_VERSION() . ' (runtime ' . XML::LibXML::LIBXML_RUNTIME_VERSION() . ')' };
print "# libxml2: ", ($libxml // 'n/a'), "\n";
my $libxslt = eval { require XML::LibXSLT; XML::LibXSLT::LIBXSLT_DOTTED_VERSION() };
print "# libxslt: ", ($libxslt // 'n/a'), "\n";
print "# Unicode (perl core): ", (eval { require Unicode::UCD; Unicode::UCD::UnicodeVersion() } // '?'), "\n";
print "# Unicode::Collate UCA: ", (eval { require Unicode::Collate; Unicode::Collate->new->version } // '?'), "\n";
print "# Unicode::LineBreak (sombok) UnicodeVersion: ",
  (eval { require Unicode::LineBreak; Unicode::LineBreak::UNICODE_VERSION() } // "?"),
  " sombok ", (eval { Unicode::LineBreak::SOMBOK_VERSION() } // "?"), "\n";

# Load biber and everything it uses, then report every loaded module.
{
  local $SIG{__WARN__} = sub {};
  require Biber; require Biber::Config; require Biber::Utils;
  require Biber::Output::bbl; require Biber::Output::bibtex;
  require Biber::Output::biblatexml; require Biber::Output::bblxml;
  require Biber::Output::dot; require Biber::Input::file::bibtex;
  require Biber::Input::file::biblatexml; require Biber::LaTeX::Recode;
  for my $m (qw(LWP::UserAgent LWP::Protocol::https Business::ISBN Business::ISSN
                Business::ISMN Lingua::Translit Text::CSV Text::CSV_XS IO::String
                Encode::EUCJPASCII Encode::JIS2K Encode::HanExtra Text::Roman
                Unicode::GCString PerlIO::utf8_strict List::MoreUtils::XS
                Mozilla::CA Data::Uniqid Parse::RecDescent XML::LibXML::Simple
                XML::Writer Sort::Key DateTime::Calendar::Julian
                DateTime::Format::Builder Class::Accessor Data::Dump Data::Compare
                Regexp::Common Log::Log4perl autovivification IPC::Run3
                File::Slurper List::AllUtils Text::BibTeX Unicode::Collate::Locale
                Test::More Test::Differences File::Which Module::Build)) {
    eval "require $m; 1";
  }
}
my %seen;
for my $f (sort keys %INC) {
  next unless $f =~ /\.pm$/;
  next if $f =~ m{^Biber[/.]};
  (my $m = $f) =~ s{/}{::}g; $m =~ s/\.pm$//;
  no strict 'refs';
  my $v = ${"${m}::VERSION"};
  $v = 'undef' unless defined $v;
  my $where = $INC{$f} // '';
  my $kind = $where =~ m{/site_perl/} ? 'site' : 'core';
  printf "%-50s %-16s %s\n", $m, $v, $kind;
}
