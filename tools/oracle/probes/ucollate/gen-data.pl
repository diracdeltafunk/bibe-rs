#!/usr/bin/env perl
# Generate the data files of crates/ucollate from the Unicode::Collate 1.31
# installation of oracle O3 (perl 5.42.0; see tools/oracle/README.md).
#
#   vendor/perl/bin/perl tools/oracle/probes/ucollate/gen-data.pl crates/ucollate/data
#
# Outputs (all plain text, LF line endings, deterministic):
#   allkeys-13.0.0.txt  verbatim copy of Unicode/Collate/allkeys.txt (DUCET 13.0.0)
#   locales.txt         the 87 Unicode/Collate/Locale/*.pl tailorings: scalar options,
#                       suppress lists, overrideCJK table names and the `entry` lines
#                       (allkeys syntax, comments stripped)
#   cjk.txt             the weights returned by the seven Unicode::Collate::CJK::*
#                       overrideCJK callbacks, queried for every code point that
#                       UCA 43 treats as a CJK unified ideograph (plus the full
#                       CJK/compatibility blocks, for safety)
#
# The tables are *data* extracted by running the modules; no module code is
# translated. See crates/ucollate/DATA.md for provenance and licences.
use strict;
use warnings;
use Unicode::Collate 1.31;
use Unicode::Collate::Locale;
use File::Basename qw(dirname);
use File::Copy qw(copy);
use Digest::SHA;

my $out = shift or die "usage: $0 OUTDIR\n";
-d $out or die "$out: not a directory\n";

$Unicode::Collate::VERSION eq '1.31' or die "need Unicode::Collate 1.31, have $Unicode::Collate::VERSION\n";
$Unicode::Collate::Locale::VERSION eq '1.31' or die "need Unicode::Collate::Locale 1.31\n";

(my $ucdir = $INC{'Unicode/Collate/Locale.pm'}) =~ s{/Locale\.pm\z}{};
# allkeys.txt and Locale/*.pl live in the arch-independent lib dir.
my ($libdir) = grep { -e "$_/Unicode/Collate/allkeys.txt" } @INC;
defined $libdir or die "allkeys.txt not found in \@INC\n";
my $base = "$libdir/Unicode/Collate";

# ---------------------------------------------------------------- allkeys
copy("$base/allkeys.txt", "$out/allkeys-13.0.0.txt") or die "copy allkeys: $!";

sub strip_entry {
    my ($entry) = @_;
    my @lines;
    for my $l (split /\n/, $entry) {
        $l =~ s/#.*//;
        $l =~ s/\s+\z//;
        $l =~ s/^\s+//;
        next if $l eq '';
        my ($k, $v) = split /\s*;\s*/, $l, 2;
        $k = join ' ', split ' ', $k;
        $v =~ s/\s+//g;
        push @lines, "$k;$v";
    }
    return @lines;
}

# ---------------------------------------------------------------- locales
my %cjk_used;
open my $lfh, '>:raw', "$out/locales.txt" or die $!;
print $lfh "# Generated by tools/oracle/probes/ucollate/gen-data.pl from Unicode::Collate::Locale 1.31.\n";
print $lfh "# Format: '\@locale <file stem>' starts a tailoring; '\@<option> <value>' lines; then entry lines 'CPS;CES'.\n";
for my $f (sort glob "$base/Locale/*.pl") {
    my ($stem) = $f =~ m{/([^/]+)\.pl\z};
    my $h = do $f or die "$f: $@ $!";
    print $lfh "\@locale $stem\n";
    for my $k (sort keys %$h) {
        next if $k eq 'entry';
        my $v = $h->{$k};
        if ($k eq 'suppress') {
            print $lfh "\@suppress ", join(' ', map { sprintf '%04X', $_ } @$v), "\n";
        } elsif ($k eq 'overrideCJK') {
            require B;
            my $gv = B::svref_2object($v)->GV;
            my $name = $gv->STASH->NAME . '::' . $gv->NAME;
            my ($table) = $name =~ /^Unicode::Collate::CJK::(\w+)::weight\w+\z/ or die "odd overrideCJK $name";
            $cjk_used{$table} = $v;
            print $lfh "\@overrideCJK $table\n";
        } elsif (ref $v) {
            die "$stem: unexpected ref option $k";
        } else {
            print $lfh "\@$k $v\n";
        }
    }
    print $lfh "$_\n" for strip_entry($h->{entry} // '');
}
close $lfh;

# ---------------------------------------------------------------- CJK
# Every code point that might be handed to an overrideCJK callback.
my @ranges = ([0x3400, 0x4DBF], [0x4E00, 0x9FFF], [0xF900, 0xFAFF], [0x20000, 0x2FFFF], [0x30000, 0x3134F]);
open my $cfh, '>:raw', "$out/cjk.txt" or die $!;
print $cfh "# Generated by tools/oracle/probes/ucollate/gen-data.pl from Unicode::Collate::CJK::* 1.31.\n";
print $cfh "# '\@table NAME' then either runs 'W CP CP ...' (CP gets primary W, W+1, ... in hex)\n";
print $cfh "# or, for multi-element results, 'CP=ITEM ITEM ...' (ITEM: hex primary or [w1.w2.w3.w4]).\n";
for my $table (sort keys %cjk_used) {
    my $fn = $cjk_used{$table};
    print $cfh "\@table $table\n";
    my (%simple, @complex);
    for my $r (@ranges) {
        for my $cp ($r->[0] .. $r->[1]) {
            my @res = $fn->($cp);
            next if !@res || (@res == 1 && !defined $res[0]);
            if (@res == 1 && !ref $res[0]) {
                $simple{$cp} = $res[0];
            } else {
                push @complex, sprintf('%04X=%s', $cp, join ' ', map {
                    defined $_ or die "undef item"; ref $_ ? '[' . join('.', map { sprintf '%04X', $_ } @$_) . ']' : sprintf('%04X', $_)
                } @res);
            }
        }
    }
    # runs of consecutive weights, ordered by weight
    my @cps = sort { $simple{$a} <=> $simple{$b} || $a <=> $b } keys %simple;
    my @line;
    my $prev;
    for my $cp (@cps) {
        my $w = $simple{$cp};
        if (!@line || $w != $prev + 1 || @line >= 17) {
            print $cfh join(' ', @line), "\n" if @line;
            @line = (sprintf('%04X', $w));
        }
        push @line, sprintf '%04X', $cp;
        $prev = $w;
    }
    print $cfh join(' ', @line), "\n" if @line;
    print $cfh "$_\n" for @complex;
}
close $cfh;

for my $f (qw(allkeys-13.0.0.txt locales.txt cjk.txt)) {
    my $sha = Digest::SHA->new(256)->addfile("$out/$f")->hexdigest;
    printf "%-20s %s\n", $f, $sha;
}
