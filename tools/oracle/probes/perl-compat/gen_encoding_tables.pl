#!/usr/bin/env perl
# Generate crates/perl-compat/src/tables/encodings.rs: the single-byte
# encodings of Perl's Encode (as bundled with biber 2.22, oracle O3) that
# biber can use for --input-encoding/--output-encoding, with their aliases
# as Encode::find_encoding resolves them (plus biber's own define_alias
# calls, Constants.pm:367-375).
#
# Usage: vendor/perl/bin/perl tools/oracle/probes/perl-compat/gen_encoding_tables.pl \
#          > crates/perl-compat/src/tables/encodings.rs
use strict;
use warnings;
use Encode qw(find_encoding encode decode FB_QUIET);
use Encode::Alias;

# biber's aliases (Constants.pm:367-375)
define_alias('ansinew'        => 'cp1252');
define_alias('applemac'       => 'MacRoman');
define_alias('applemacce'     => 'MacCentralEurRoman');
define_alias('next'           => 'MacRoman');
define_alias('x-mac-roman'    => 'MacRoman');
define_alias('x-mac-centeuro' => 'MacCentralEurRoman');
define_alias('x-mac-cyrillic' => 'MacCyrillic');
define_alias('x-nextstep'     => 'MacRoman');
define_alias('x-ascii'        => 'ascii');

my @encs = (
  'ascii', 'iso-8859-1',
  (map { "iso-8859-$_" } 2 .. 11, 13 .. 16),
  (map { "cp$_" } 437, 850, 852, 855, 857, 858, 860 .. 866, 869, 874, 1250 .. 1258),
  'koi8-r', 'koi8-u', 'koi8-f',
  qw(MacRoman MacCentralEurRoman MacCyrillic MacGreek MacTurkish MacIcelandic
     MacCroatian MacRomanian MacUkrainian MacRumanian viscii hp-roman8 nextstep),
);

# Candidate spellings to resolve through find_encoding.
my @cands;
for my $n (1 .. 16) {
  push @cands, "latin$n", "l$n", "iso-8859-$n", "iso8859-$n", "iso_8859-$n",
    "iso8859$n", "iso-8859$n", "iso_8859_$n", "iso8859_$n", "8859-$n", "8859$n";
}
for my $n (437, 850, 852, 855, 857, 858, 860 .. 866, 869, 874, 1250 .. 1258) {
  push @cands, "cp$n", "cp-$n", "cp_$n", "windows-$n", "windows$n", "win$n",
    "win-$n", "ibm-$n", "ibm$n", "ibm_$n", "ms-$n", "ms$n", "cp$n-dos";
}
push @cands, qw(ascii us-ascii x-ascii ansi_x3.4-1968 iso-646-us iso646-us us
  ansinew applemac applemacce next x-mac-roman x-mac-centeuro x-mac-cyrillic
  x-nextstep macintosh mac koi8-r koi8r koi8-u koi8u koi8-f koi8f viscii hp-roman8
  roman8 nextstep winlatin1 winlatin2 wincyrillic wingreek winturkish winbaltic
  cyrillic greek arabic hebrew thai latin-1 latin-2 latin-9 latin_1 latin_9
  iso-latin-1 iso_latin_1 isolatin1 l1 l2 l9 iso-8859-1 iso-ir-100);
push @cands, @encs, map { lc } @encs;

my %canon;    # canonical name -> 1
my %alias;    # lc alias -> canonical name
for my $e (@encs) {
  my $o = find_encoding($e) or die "no encoding $e";
  $canon{$o->name} = 1;
}
for my $c (@cands) {
  my $o = find_encoding($c) or next;
  next unless $canon{$o->name};
  $alias{lc $c} = $o->name;
}

print "//! Generated by tools/oracle/probes/perl-compat/gen_encoding_tables.pl from\n";
print "//! Perl Encode $Encode::VERSION (oracle O3). Do not edit.\n\n";
print "/// One single-byte encoding: `decode[b]` is the code point of byte `b`\n";
print "/// (`u32::MAX` if undefined); `encode` maps code points to bytes, sorted.\n";
print "pub(crate) struct ByteEncoding {\n    pub name: &'static str,\n";
print "    pub decode: [u32; 256],\n    pub encode: &'static [(u32, u8)],\n}\n\n";
print "pub(crate) static ENCODINGS: &[ByteEncoding] = &[\n";
for my $name (sort keys %canon) {
  my @dec;
  for my $b (0 .. 255) {
    my $bytes = chr($b);
    my $s = decode($name, $bytes, FB_QUIET);
    push @dec, (defined $s && length($s) == 1) ? ord($s) : 4294967295;
  }
  my @enc;
  for my $cp (0 .. 0xFFFF) {
    next if $cp >= 0xD800 && $cp <= 0xDFFF;
    my $str = chr($cp);
    my $b = encode($name, $str, FB_QUIET);
    next unless defined $b && length($b) == 1 && length($str) == 0;
    push @enc, [$cp, ord($b)];
  }
  print "    ByteEncoding {\n        name: \"$name\",\n        decode: [";
  print join(', ', @dec);
  print "],\n        encode: &[";
  print join(', ', map { "($_->[0], $_->[1])" } @enc);
  print "],\n    },\n";
}
print "];\n\n";
print "/// Lower-cased alias → canonical name (`Encode::find_encoding`).\n";
print "pub(crate) static ALIASES: &[(&str, &str)] = &[\n";
for my $a (sort keys %alias) {
  print "    (\"$a\", \"$alias{$a}\"),\n";
}
print "];\n";
