#!/usr/bin/env perl
# Generates the Unicode tables of crates/perl-compat from the O3 oracle perl
# (perl 5.42.0, Unicode 16.0.0) and from sombok 2.4.0's Unicode 8.0.0
# property table (as bundled in Unicode-LineBreak 2019.001).
#
# Run from the repository root:
#   vendor/perl/bin/perl tools/oracle/probes/perl-compat/gen_unicode_tables.pl \
#       [path/to/sombok/lib/8.0.0.c]
#
# Writes crates/perl-compat/src/tables/{case,props,num,gcb16,gcb8}.rs.
# The tables are derived by *asking perl* (lc/uc/fc/ucfirst, regex classes,
# Unicode::UCD::num), so they reproduce exactly what biber's perl does.
use v5.24;
use strict;
use warnings;
no warnings qw(surrogate nonchar non_unicode utf8);
use Unicode::UCD qw(num prop_invmap prop_invlist charinfo);
use File::Glob qw(bsd_glob);

my $out = 'crates/perl-compat/src/tables';
-d $out or die "run from the repository root ($out missing)\n";

my $MAX = 0x10FFFF;
my $HEADER = "// \@generated by tools/oracle/probes/perl-compat/gen_unicode_tables.pl\n"
  . "// from perl $^V (Unicode " . Unicode::UCD::UnicodeVersion() . "). Do not edit.\n\n";

sub rs_str {
  my $s = shift;
  return '"' . join('', map { sprintf('\\u{%x}', ord $_) } split //, $s) . '"';
}

sub write_file {
  my ($name, $body) = @_;
  open my $fh, '>:utf8', "$out/$name" or die "$out/$name: $!";
  print $fh $HEADER, $body;
  close $fh;
  say STDERR "wrote $out/$name";
}

sub is_surrogate { my $c = shift; return $c >= 0xD800 && $c <= 0xDFFF }

# ---------------------------------------------------------------- case
{
  my %fn = (
    LOWER => sub { lc $_[0] },
    UPPER => sub { uc $_[0] },
    FOLD  => sub { fc $_[0] },
    TITLE => sub { ucfirst $_[0] },
  );
  my $body = '';
  for my $name (qw(LOWER UPPER FOLD TITLE)) {
    my $f = $fn{$name};
    my @ent;
    for my $cp (0 .. $MAX) {
      next if is_surrogate($cp);
      my $c = chr $cp;
      my $m = $f->($c);
      push @ent, sprintf("(0x%x, %s)", $cp, rs_str($m)) if $m ne $c;
    }
    $body .= "pub(crate) static $name: &[(u32, &str)] = &[\n";
    $body .= join('', map { "    $_,\n" } @ent);
    $body .= "];\n\n";
  }
  write_file('case.rs', $body);
}

# ---------------------------------------------------------------- props
{
  my @props = (
    [PERL_SPACE => '\s'],   [PERL_DIGIT => '\d'],   [PERL_WORD => '\w'],
    [PERL_HSPACE => '\h'],  [PERL_VSPACE => '\v'],
    [L => '\p{L}'], [LU => '\p{Lu}'], [LL => '\p{Ll}'], [LT => '\p{Lt}'],
    [LM => '\p{Lm}'], [LO => '\p{Lo}'],
    [M => '\p{M}'], [MN => '\p{Mn}'], [MC => '\p{Mc}'], [ME => '\p{Me}'],
    [N => '\p{N}'], [ND => '\p{Nd}'], [NL => '\p{Nl}'], [NO => '\p{No}'],
    [P => '\p{P}'], [PC => '\p{Pc}'], [PD => '\p{Pd}'], [PS => '\p{Ps}'],
    [PE => '\p{Pe}'], [PI => '\p{Pi}'], [PF => '\p{Pf}'], [PO => '\p{Po}'],
    [S => '\p{S}'], [SM => '\p{Sm}'], [SC => '\p{Sc}'], [SK => '\p{Sk}'], [SO => '\p{So}'],
    [Z => '\p{Z}'], [ZS => '\p{Zs}'], [C => '\p{C}'], [CC => '\p{Cc}'], [CF => '\p{Cf}'],
    [CN => '\p{Cn}'],
    [DASH => '\p{Dash}'], [DIA => '\p{Dia}'], [ALPHA => '\p{Alpha}'],
    [UPPER => '\p{Upper}'], [LOWER => '\p{Lower}'], [ASCII_HEX_DIGIT => '\p{ASCII_Hex_Digit}'],
  );
  my $body = '';
  for my $p (@props) {
    my ($name, $re) = @$p;
    my $qr = qr/\A$re\z/;
    my @ranges;
    my $start;
    for my $cp (0 .. $MAX + 1) {
      my $in = $cp <= $MAX && chr($cp) =~ $qr;
      if ($in && !defined $start) { $start = $cp }
      elsif (!$in && defined $start) { push @ranges, [$start, $cp - 1]; undef $start }
    }
    $body .= "/// Perl `$re`\n";
    $body .= "pub(crate) static $name: &[(u32, u32)] = &[\n";
    my @items = map { sprintf("(0x%x, 0x%x)", @$_) } @ranges;
    while (my @line = splice(@items, 0, 6)) { $body .= '    ' . join(', ', @line) . ",\n" }
    $body .= "];\n\n";
    say STDERR "  $name: " . scalar(@ranges) . " ranges";
  }
  {
    # quotemeta (on character strings): which code points get a backslash
    my @ranges;
    my $start;
    for my $cp (0 .. $MAX + 1) {
      my $in = 0;
      if ($cp <= $MAX) { my $c = chr $cp; utf8::upgrade($c); $in = quotemeta($c) ne $c }
      if ($in && !defined $start) { $start = $cp }
      elsif (!$in && defined $start) { push @ranges, [$start, $cp - 1]; undef $start }
    }
    $body .= "/// Characters perl's `quotemeta` backslashes (character strings)\n";
    $body .= "pub(crate) static QUOTEMETA: &[(u32, u32)] = &[\n";
    my @items = map { sprintf("(0x%x, 0x%x)", @$_) } @ranges;
    while (my @line = splice(@items, 0, 6)) { $body .= '    ' . join(', ', @line) . ",\n" }
    $body .= "];\n\n";
  }
  {
    # Unicode blocks for \p{InX}: every alias, loosely normalised
    # (lower case, no spaces, underscores or hyphens).
    my $blocks = Unicode::UCD::charblocks();
    my %seen;
    my @ent;
    for my $name (sort keys %$blocks) {
      my ($lo, $hi) = @{ $blocks->{$name}[0] }[0, 1];
      my @aliases = ($name, Unicode::UCD::prop_value_aliases('Block', $name));
      for my $a (@aliases) {
        next unless defined $a;
        (my $k = lc $a) =~ s/[\s_-]//g;
        next if $seen{$k}++;
        push @ent, sprintf('("%s", 0x%x, 0x%x)', $k, $lo, $hi);
      }
    }
    @ent = sort @ent;
    $body .= "/// Unicode blocks (`\\p{InName}`), keyed by loosely normalised alias\n";
    $body .= "pub(crate) static BLOCKS: &[(&str, u32, u32)] = &[\n" . join('', map { "    $_,\n" } @ent) . "];\n\n";
  }
  write_file('props.rs', $body);
}

# ---------------------------------------------------------------- num
{
  my @ent;
  for my $cp (0 .. $MAX) {
    next if is_surrogate($cp);
    my $v = num(chr $cp);
    next unless defined $v;
    if ($v == int($v) && abs($v) < 9e18) {
      push @ent, sprintf("(0x%x, NumVal::Int(%d))", $cp, $v);
    }
    else {
      my $r = charinfo($cp)->{numeric};
      my ($n, $d) = split m{/}, $r;
      die "unexpected numeric $r for $cp" unless defined $d;
      my $check = $n / $d;
      die "mismatch $cp: $check vs $v" unless $check == $v;
      push @ent, sprintf("(0x%x, NumVal::Frac(%d, %d))", $cp, $n, $d);
    }
  }
  my $body = "use crate::unicode::NumVal;\n\n/// `Unicode::UCD::num` of every single code point that has a value.\n";
  $body .= "pub(crate) static NUMERIC: &[(u32, NumVal)] = &[\n" . join('', map { "    $_,\n" } @ent) . "];\n";
  write_file('num.rs', $body);
}

# ---------------------------------------------------------------- gcb16
{
  # perl's own prop_invmap('GCB') merges in perl-internal values (ExtPict_XX,
  # InCB_*), so build the standard property from the per-value inversion lists.
  my %short = (
    CR => 'Cr', LF => 'Lf', Control => 'Control', Extend => 'Extend', ZWJ => 'Zwj',
    Regional_Indicator => 'RegionalIndicator', Prepend => 'Prepend',
    SpacingMark => 'SpacingMark', L => 'L', V => 'V', T => 'T', LV => 'Lv', LVT => 'Lvt',
  );
  my @raw;
  for my $v (sort keys %short) {
    my @inv = prop_invlist("GCB=$v");
    for (my $i = 0; $i < @inv; $i += 2) {
      my $end = defined $inv[$i + 1] ? $inv[$i + 1] - 1 : $MAX;
      push @raw, [$inv[$i], $end, $short{$v}];
    }
  }
  @raw = sort { $a->[0] <=> $b->[0] } @raw;
  for my $i (1 .. $#raw) { die "overlap" if $raw[$i][0] <= $raw[$i - 1][1] }
  my @ent = map { sprintf("(0x%x, 0x%x, Gcb16::%s)", @$_) } @raw;
  my $body = "use crate::grapheme::Gcb16;\n\n";
  $body .= "pub(crate) static GCB: &[(u32, u32, Gcb16)] = &[\n" . join('', map { "    $_,\n" } @ent) . "];\n\n";
  for my $p (['EXT_PICT', 'ExtPict'], ['INCB_LINKER', 'InCB=Linker'],
             ['INCB_CONSONANT', 'InCB=Consonant'], ['INCB_EXTEND', 'InCB=Extend']) {
    my ($name, $prop) = @$p;
    my @inv = prop_invlist($prop);
    my @r;
    for (my $i = 0; $i < @inv; $i += 2) {
      my $end = defined $inv[$i + 1] ? $inv[$i + 1] - 1 : $MAX;
      push @r, sprintf("(0x%x, 0x%x)", $inv[$i], $end);
    }
    $body .= "pub(crate) static $name: &[(u32, u32)] = &[\n";
    while (my @line = splice(@r, 0, 6)) { $body .= '    ' . join(', ', @line) . ",\n" }
    $body .= "];\n\n";
  }
  write_file('gcb16.rs', $body);
}

# ---------------------------------------------------------------- gcb8 (sombok)
{
  my $src = shift @ARGV;
  unless ($src) {
    ($src) = bsd_glob('vendor/perl-build/cpanm-home/work/*/Unicode-LineBreak-2019.001/sombok/lib/8.0.0.c');
  }
  die "sombok 8.0.0.c not found; pass its path\n" unless $src && -e $src;
  open my $fh, '<', $src or die "$src: $!";
  my $c = do { local $/; <$fh> };
  my ($idx) = $c =~ /linebreak_prop_index\[\]\s*=\s*\{(.*?)\};/s or die "no index";
  my ($arr) = $c =~ /linebreak_prop_array\[\]\s*=\s*\{(.*?)\};/s or die "no array";
  my @index = $idx =~ /(\d+)/g;
  my @array = $arr =~ /([A-Z]{2}_\w+)/g;
  die "array not quads" if @array % 4;
  my %gbmap = (
    GB_CR => 'Cr', GB_LF => 'Lf', GB_Control => 'Control', GB_Extend => 'Extend',
    GB_Prepend => 'Prepend', GB_SpacingMark => 'SpacingMark', GB_L => 'L', GB_V => 'V',
    GB_T => 'T', GB_LV => 'Lv', GB_LVT => 'Lvt', GB_Other => 'Other', GB_Virama => 'Virama',
    GB_OtherLetter => 'OtherLetter', GB_Regional_Indicator => 'RegionalIndicator',
  );
  my (@gb, @sp);
  for my $cp (0 .. $MAX) {
    my ($lbc, $gcb);
    if ($cp < 0x20000) {
      my $e = ($index[$cp >> 5] + ($cp & 31)) * 4;
      ($lbc, $gcb) = @array[$e, $e + 2];
    }
    elsif ($cp <= 0x2FFFD || (0x30000 <= $cp && $cp <= 0x3FFFD)) { ($lbc, $gcb) = ('LB_ID', 'GB_Other') }
    elsif ($cp == 0xE0001 || (0xE0020 <= $cp && $cp <= 0xE007F)) { ($lbc, $gcb) = ('LB_CM', 'GB_Control') }
    elsif (0xE0100 <= $cp && $cp <= 0xE01EF) { ($lbc, $gcb) = ('LB_CM', 'GB_Extend') }
    elsif ((0xF0000 <= $cp && $cp <= 0xFFFFD) || (0x100000 <= $cp && $cp <= 0x10FFFD)) { ($lbc, $gcb) = ('LB_AL', 'GB_Other') }
    else { ($lbc, $gcb) = ('LB_AL', 'GB_Control') }
    my $g = $gbmap{$gcb} // die "unknown $gcb";
    if (@gb && $gb[-1][2] eq $g && $gb[-1][1] == $cp - 1) { $gb[-1][1] = $cp }
    else { push @gb, [$cp, $cp, $g] }
    if ($lbc eq 'LB_SP') {
      if (@sp && $sp[-1][1] == $cp - 1) { $sp[-1][1] = $cp } else { push @sp, [$cp, $cp] }
    }
  }
  my $body = "// sombok 2.4.0 (Unicode::LineBreak 2019.001) property table, Unicode 8.0.0\n";
  $body .= "use crate::grapheme::Gcb8;\n\n";
  $body .= "pub(crate) static GCB: &[(u32, u32, Gcb8)] = &[\n";
  $body .= join('', map { sprintf("    (0x%x, 0x%x, Gcb8::%s),\n", @$_) } grep { $_->[2] ne 'Other' } @gb);
  $body .= "];\n\n/// Code points with line-break class SP.\n";
  $body .= "pub(crate) static LB_SP: &[(u32, u32)] = &[\n";
  $body .= join('', map { sprintf("    (0x%x, 0x%x),\n", @$_) } @sp);
  $body .= "];\n";
  write_file('gcb8.rs', $body);
}
