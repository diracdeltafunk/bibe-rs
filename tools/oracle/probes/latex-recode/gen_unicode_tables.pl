#!/usr/bin/env perl
# Generates crates/latex-recode/src/unicode_tables.rs from the O3 perl (5.42.0,
# Unicode 16.0.0), so that the character classes used by Biber::LaTeX::Recode's
# regexes (\s \w \d \pL \pM and the \X grapheme-cluster properties) are exactly
# Perl's.
#
#   vendor/perl/bin/perl tools/oracle/probes/latex-recode/gen_unicode_tables.pl \
#       > crates/latex-recode/src/unicode_tables.rs
use v5.24;
use strict;
no warnings;
use Unicode::UCD;

my %classes = (
  SPACE  => qr/\A\s\z/,
  WORD   => qr/\A\w\z/,
  DIGIT  => qr/\A\d\z/,
  LETTER => qr/\A\pL\z/,
  MARK   => qr/\A\pM\z/,
  EXT_PICT => qr/\A\p{Extended_Pictographic}\z/,
);
my @gcb = qw(CR LF Control Extend ZWJ Regional_Indicator Prepend SpacingMark L V T LV LVT);
my @incb = qw(Consonant Extend Linker);

my %ranges;   # name => [[lo,hi],...]
my @gcb_r;    # [lo,hi,value]
my @incb_r;

sub push_range {
  my ($list, $cp, @val) = @_;
  if (@$list && $list->[-1][1] == $cp - 1 && "@{$list->[-1]}[2..$#{$list->[-1]}]" eq "@val") {
    $list->[-1][1] = $cp;
  } else {
    push @$list, [$cp, $cp, @val];
  }
}

my %gcb_re = map { $_ => qr/\A\p{GCB=$_}\z/ } @gcb;
my %incb_re = map { $_ => qr/\A\p{InCB=$_}\z/ } @incb;

for my $cp (0 .. 0x10FFFF) {
  my $c = chr($cp);
  for my $n (sort keys %classes) {
    push_range($ranges{$n} //= [], $cp) if $c =~ $classes{$n};
  }
  for my $g (@gcb) {
    if ($c =~ $gcb_re{$g}) { push_range(\@gcb_r, $cp, $g); last }
  }
  for my $g (@incb) {
    if ($c =~ $incb_re{$g}) { push_range(\@incb_r, $cp, $g); last }
  }
}

sub fmt_cp { $_[0] >= 0xD800 && $_[0] <= 0xDFFF ? undef : sprintf("'\\u{%X}'", $_[0]) }

print "// Generated by tools/oracle/probes/latex-recode/gen_unicode_tables.pl from perl $^V\n";
print "// (Unicode ", Unicode::UCD::UnicodeVersion(), "). Do not edit by hand.\n\n";
print "use crate::unicode::{Gcb, InCb};\n\n";
for my $n (sort keys %ranges) {
  my @r = grep { !($_->[0] >= 0xD800 && $_->[1] <= 0xDFFF) } $ranges{$n}->@*;
  print "pub(crate) static $n: &[(u32, u32)] = &[\n";
  printf("    (0x%X, 0x%X),\n", $_->[0], $_->[1]) for @r;
  print "];\n\n";
}
print "pub(crate) static GCB: &[(u32, u32, Gcb)] = &[\n";
printf("    (0x%X, 0x%X, Gcb::%s),\n", $_->[0], $_->[1], $_->[2]) for @gcb_r;
print "];\n\n";
print "pub(crate) static INCB: &[(u32, u32, InCb)] = &[\n";
printf("    (0x%X, 0x%X, InCb::%s),\n", $_->[0], $_->[1], $_->[2]) for @incb_r;
print "];\n";
