#!/usr/bin/env python3
"""Write THIRD-PARTY-LICENSES.md: the licences and notices of everything
compiled into the `bibers` binary that bibe-rs did not write.

    tools/release/third_party_licenses.py [OUTPUT]   (default THIRD-PARTY-LICENSES.md)

Covers every crate in `bibers`'s normal dependency tree on the release targets (from
`cargo tree` and `cargo metadata`, so it follows Cargo.lock), with the licence
files each crate ships, plus the C libraries bundled inside crates (PCRE2 and
its sljit JIT in pcre2-sys, mimalloc in libmimalloc-sys), whose notices are
only in their source files. The release workflow runs this and puts the file
in every archive (MIT/BSD-style licences require the notices to accompany
binaries). The data notices for what bibers' own crates embed are in NOTICE.md.
"""

import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LICENCE_FILE = re.compile(r"^(LICEN[CS]E|COPYING|NOTICE|UNLICENSE)", re.I)


def run(*cmd):
    return subprocess.run(cmd, cwd=ROOT, check=True, capture_output=True, text=True).stdout


# The release targets (.github/workflows/release.yml).
TARGETS = (
    "x86_64-unknown-linux-musl",
    "aarch64-unknown-linux-musl",
    "x86_64-apple-darwin",
    "aarch64-apple-darwin",
    "x86_64-pc-windows-msvc",
)


def shipped_packages():
    """(name, version) of every package linked into bibers on a release target."""
    pkgs = set()
    for target in TARGETS:
        out = run(
            "cargo", "tree", "-p", "bibers", "-e", "normal", "--target", target,
            "--prefix", "none", "--format", "{p}", "--locked",
        )
        for line in out.splitlines():
            m = re.match(r"^(\S+) v(\S+)", line.strip())
            if m:
                pkgs.add((m[1], m[2]))
    return pkgs


def c_header(path, start_pat):
    """The licence comment at the top of a C source file."""
    text = Path(path).read_text(encoding="utf-8", errors="replace")
    # the first comment block that carries the licence (not a banner)
    blocks = re.findall(r"/\*(.*?)\*/", text[:8000], re.S)
    body = next((b for b in blocks if "Redistribution" in b), "")
    lines = [re.sub(r"^\s?\*? ?", "", l).rstrip() for l in body.splitlines()]
    lines = [l for l in lines if not re.fullmatch(r"\*+", l.strip())]
    i = next((k for k, l in enumerate(lines) if re.search(start_pat, l)), 0)
    return "\n".join(lines[i:]).strip()


def main():
    out_path = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "THIRD-PARTY-LICENSES.md"
    meta = json.loads(run("cargo", "metadata", "--format-version", "1", "--locked"))
    by_key = {(p["name"], p["version"]): p for p in meta["packages"]}
    pkgs = sorted(k for k in shipped_packages() if by_key.get(k, {}).get("source"))

    texts = {}  # sha → (text, [crates])
    rows = []
    bundled = []
    for name, version in pkgs:
        p = by_key[(name, version)]
        d = Path(p["manifest_path"]).parent
        files = sorted(f for f in d.iterdir() if f.is_file() and LICENCE_FILE.match(f.name))
        lic = p.get("license") or "see licence file"
        rows.append((name, version, lic, p.get("repository") or ""))
        for f in files:
            t = f.read_text(encoding="utf-8", errors="replace").strip()
            h = hashlib.sha256(re.sub(r"\s+", " ", t).encode()).hexdigest()
            texts.setdefault(h, (t, []))[1].append(f"{name} {version} ({f.name})")
        if not files:
            texts.setdefault(
                "none-" + name, (f"(No licence file shipped; licence: {lic}.)", [])
            )[1].append(f"{name} {version}")
        if name == "pcre2-sys":
            up = d / "upstream"
            bundled.append(("PCRE2 (bundled in pcre2-sys)",
                            c_header(up / "src/pcre2_compile.c", r"Written by|Copyright")))
            sl = up / "deps/sljit/sljit_src/sljitLir.c"
            if sl.exists():
                bundled.append(("sljit (PCRE2's JIT compiler, bundled in pcre2-sys)",
                                c_header(sl, r"Copyright")))
        if name == "libmimalloc-sys":
            for v in ("v3", "v2"):
                lf = d / "c_src/mimalloc" / v / "LICENSE"
                if lf.exists():
                    bundled.append((f"mimalloc {v} (bundled in libmimalloc-sys)",
                                    lf.read_text(encoding="utf-8").strip()))
                    break

    out = [
        "# Third-party licences",
        "",
        "The `bibers` binary is distributed under the Artistic License 2.0 (`LICENSE`), with the"
        " notices in `NOTICE.md`. It also contains the following third-party software, under the"
        " licences reproduced below. Generated by `tools/release/third_party_licenses.py` from"
        " `Cargo.lock`.",
        "",
        "## Crates",
        "",
        "| Crate | Version | Licence |",
        "|---|---|---|",
    ]
    for name, version, lic, repo in rows:
        crate = f"[{name}]({repo})" if repo else name
        out.append(f"| {crate} | {version} | {lic} |")
    out += ["", "## Bundled C libraries", ""]
    for title, text in bundled:
        out += [f"### {title}", "", "```text", text, "```", ""]
    out += ["## Licence texts", ""]
    for _, (text, who) in sorted(texts.items(), key=lambda kv: kv[1][1][0]):
        out += ["Used by: " + ", ".join(who), "", "```text", text, "```", ""]
    out_path.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {out_path}: {len(rows)} crates, {len(bundled)} bundled C libraries, "
          f"{len(texts)} distinct licence texts")


if __name__ == "__main__":
    main()
