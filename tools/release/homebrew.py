#!/usr/bin/env python3
"""Write the Homebrew formula for a bibers release.

    tools/release/homebrew.py VERSION [SHA256SUMS] > Formula/bibers.rb

The formula installs the release's prebuilt binaries (macOS universal, Linux
x86_64/aarch64 musl) for the tap diracdeltafunk/homebrew-tap, so that
`brew install diracdeltafunk/tap/bibers` needs no compiler. The checksums come
from the release's SHA256SUMS: a local file, or downloaded with `gh` when
omitted. Files Homebrew downloads are not quarantined by macOS, so the
unsigned binary runs without a Gatekeeper prompt.
"""

import subprocess
import sys
import tempfile
from pathlib import Path

REPO = "diracdeltafunk/bibe-rs"

TEMPLATE = '''\
# Generated by tools/release/homebrew.py in {repo}; do not edit by hand.
class Bibers < Formula
  desc "Fast, biber-compatible bibliography processor for biblatex"
  homepage "https://github.com/{repo}"
  license all_of: [
    "Artistic-2.0",
    {{ any_of: ["Artistic-1.0-Perl", "GPL-1.0-or-later"] }},
    "Unicode-3.0",
  ]

  # The macOS archive is a universal binary (Apple silicon and Intel).
  on_macos do
    on_arm do
      url "https://github.com/{repo}/releases/download/v{version}/bibers-{version}-universal-apple-darwin.tar.gz"
      sha256 "{mac}"
    end
    on_intel do
      url "https://github.com/{repo}/releases/download/v{version}/bibers-{version}-universal-apple-darwin.tar.gz"
      sha256 "{mac}"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/{repo}/releases/download/v{version}/bibers-{version}-aarch64-unknown-linux-musl.tar.gz"
      sha256 "{linux_arm}"
    end
    on_intel do
      url "https://github.com/{repo}/releases/download/v{version}/bibers-{version}-x86_64-unknown-linux-musl.tar.gz"
      sha256 "{linux_x86}"
    end
  end

  def install
    bin.install "bibers"
    doc.install "README.md", "docs/compat.md"
    prefix.install "LICENSE", "NOTICE.md", "LICENSES", "THIRD-PARTY-LICENSES.md"
  end

  def caveats
    <<~EOS
      bibers is a drop-in replacement for biber 2.22 (biblatex 3.22).
      To make latexmk use it, add this line to ~/.latexmkrc:
        $biber = 'bibers %O %S';
      For other editors and build tools, see:
        https://github.com/{repo}#using-bibers-instead-of-biber
    EOS
  end

  test do
    assert_match "bibers version: #{{version}}", shell_output("#{{bin}}/bibers --version")
    (testpath/"refs.bib").write <<~BIB
      @book{{knuth,
        author = {{Knuth, Donald E.}},
        title = {{The {{\\TeX}}book}},
        date = {{1984}},
      }}
    BIB
    system bin/"bibers", "--tool", "--noconf", "refs.bib"
    assert_match "AUTHOR = {{Knuth, Donald E.}}", (testpath/"refs_bibertool.bib").read
  end
end
'''


def checksums(version, path):
    if path:
        text = Path(path).read_text()
    else:
        with tempfile.TemporaryDirectory() as d:
            subprocess.run(
                ["gh", "release", "download", f"v{version}", "--repo", REPO,
                 "-p", "SHA256SUMS", "-D", d],
                check=True,
            )
            text = (Path(d) / "SHA256SUMS").read_text()
    sums = {}
    for line in text.splitlines():
        if line.strip():
            digest, name = line.split()
            sums[name] = digest
    return sums


def main():
    if len(sys.argv) not in (2, 3):
        sys.exit(__doc__)
    version = sys.argv[1].removeprefix("v")
    sums = checksums(version, sys.argv[2] if len(sys.argv) == 3 else None)
    name = lambda platform: f"bibers-{version}-{platform}.tar.gz"
    try:
        sys.stdout.write(TEMPLATE.format(
            repo=REPO,
            version=version,
            mac=sums[name("universal-apple-darwin")],
            linux_arm=sums[name("aarch64-unknown-linux-musl")],
            linux_x86=sums[name("x86_64-unknown-linux-musl")],
        ))
    except KeyError as e:
        sys.exit(f"SHA256SUMS has no entry for {e}")


if __name__ == "__main__":
    main()
