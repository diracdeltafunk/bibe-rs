#!/usr/bin/env python3
"""Generate tests/corpus/styles/: \\nocite{*} over biblatex-examples.bib for

  1. every standard biblatex style,
  2. contributed styles installed in TeX Live (those that compile),
  3. an option matrix: one option varied at a time from three base styles
     (authoryear, alphabetic, numeric).

Each case is a small generated .tex (kept in the case dir) plus the .bcf from
one `pdflatex -draftmode` run; biblatex-examples.bib comes from
tests/corpus/shared/.

Usage: python3 tools/corpus/gen_styles.py [--list] [NAME-REGEX]
Then:  cargo xtask golden styles/
"""

import concurrent.futures as cf
import re
import shutil
import subprocess
import sys
import tempfile
from dataclasses import dataclass, field
from pathlib import Path

from corpuslib import (CORPUS, bcf_datasources, ensure_shared_examples_bib, latex_error, log,
                       run_latex, write_case)

SUITE = CORPUS / "styles"

# A few explicit citations before \nocite{*}, so citation order (sorting=none,
# labelnumbers, ibid/verbose tracking) is not just .bib order.
CITES = r"""\cite{sigfridsson,knuth:ct:a}, \cite{aristotle:poetics},
\textcite{companion}, \parencite[12]{knuth:ct:b}, \cite{westfahl:space,westfahl:frontier}.
"""


@dataclass
class Spec:
    name: str
    style: str
    options: str = ""                 # extra biblatex package options
    preamble: str = ""                # extra preamble (after biblatex)
    package: str | None = None        # load this package instead of biblatex (e.g. biblatex-chicago)
    babel: str = "american"
    engine: str = "pdflatex"
    tags: list[str] = field(default_factory=list)
    description: str = ""
    allow: list[str] = field(default_factory=list)


def tex_for(s: Spec) -> str:
    if s.package:
        opts = s.options
        load = rf"\usepackage[{opts}]{{{s.package}}}" if opts else rf"\usepackage{{{s.package}}}"
    else:
        opts = ",".join(x for x in ("backend=biber", f"style={s.style}", s.options) if x)
        load = rf"\usepackage[{opts}]{{biblatex}}"
    fontenc = "" if s.engine != "pdflatex" else "\\usepackage[T1]{fontenc}\n"
    return (
        "% Generated by tools/corpus/gen_styles.py; do not edit.\n"
        "\\documentclass{article}\n"
        f"{fontenc}"
        f"\\usepackage[{s.babel}]{{babel}}\n"
        "\\usepackage{csquotes}\n"
        f"{load}\n"
        f"{s.preamble}"
        "\\addbibresource{biblatex-examples.bib}\n"
        "\\begin{document}\n"
        f"{CITES}"
        "\\nocite{*}\n"
        "\\printbibliography\n"
        "\\end{document}\n"
    )


STANDARD = """numeric numeric-comp numeric-verb alphabetic alphabetic-verb authoryear
authoryear-comp authoryear-ibid authoryear-icomp authortitle authortitle-comp
authortitle-ibid authortitle-icomp authortitle-terse authortitle-tcomp
authortitle-ticomp verbose verbose-ibid verbose-note verbose-inote verbose-trad1
verbose-trad2 verbose-trad3 reading draft debug""".split()

# Contributed styles: name -> Spec overrides. These also compile and could be
# added, but were left out to keep the corpus small: apa6, chem-acs, lncs,
# windycity, footnote-dw, nejm, musuos (babel=ngerman).
CONTRIB = {
    "apa": dict(),
    "chicago-authordate": dict(package="biblatex-chicago", options="authordate,backend=biber"),
    "chicago-notes": dict(package="biblatex-chicago", options="notes,backend=biber"),
    "ieee": dict(),
    "mla": dict(),
    "gb7714-2015": dict(),
    "ext-authoryear": dict(),
    "nature": dict(),
    "phys": dict(),
    "science": dict(),
    "oxyear": dict(),   # biblatex-oxref: oxref.bbx is only the base; the styles are oxyear/oxnum/oxalph
    "sbl": dict(),
    "iso-authoryear": dict(),
    "philosophy-modern": dict(),
    "archaeologie": dict(babel="ngerman"),  # adds three .bib files of its own
}

BASES = ["authoryear", "alphabetic", "numeric"]

SOURCEMAPS = {
    "sourcemap-types": (
        "type and field mapping, pertype, fieldset/origfieldval",
        r"""\DeclareSourcemap{
  \maps[datatype=bibtex]{
    \map{\step[typesource=thesis, typetarget=report, final]
         \step[fieldset=type, fieldvalue={thesis converted}]}
    \map{\pertype{article}
         \step[fieldsource=journaltitle, fieldtarget=journal]}
    \map[overwrite]{\pertype{book}
         \step[fieldsource=title, final]
         \step[fieldset=usera, origfieldval]}
  }
}
"""),
    "sourcemap-regex": (
        "regex match/replace with captures and case-changing escapes",
        r"""\DeclareSourcemap{
  \maps[datatype=bibtex]{
    \map{\step[fieldsource=title, match=\regexp{\A(The|A)\s+(.+)\Z}, replace=\regexp{$2, $1}]}
    \map{\step[fieldsource=publisher, match=\regexp{University\s+Press}, replace={UP}]}
    \map{\step[fieldsource=location, match=\regexp{\A(\w)(\w+)}, replace=\regexp{\u$1\U$2}]}
  }
}
"""),
    "sourcemap-entrynull": (
        "dropping entries (entrynull), notfield, null fields, overwrite",
        r"""\DeclareSourcemap{
  \maps[datatype=bibtex]{
    \map{\step[fieldsource=keywords, match=\regexp{secondary}, final]
         \step[entrynull]}
    \map{\step[notfield=isbn, final]
         \step[fieldset=note, fieldvalue={no ISBN}, append]}
    \map[overwrite]{\step[fieldset=abstract, null]
                    \step[fieldset=annotation, null]}
  }
}
"""),
}


def matrix() -> list[Spec]:
    out = []

    def add(base, slug, opts, option, desc, preamble="", tags=(), allow=()):
        out.append(Spec(
            name=f"{base}--{slug}", style=base, options=opts, preamble=preamble,
            tags=["suite:styles", "matrix", f"style:{base}", f"option:{option}",
                  *([f"option:{opts}"] if opts and "," not in opts else []), *tags],
            description=f"\\nocite{{*}} over biblatex-examples.bib, style={base}, {desc}",
            allow=list(allow)))

    # One option varied at a time. Not every option on every base: options that
    # don't interact with the style (sourcemaps, sort locales) use authoryear only.
    for base in ["authoryear", "alphabetic"]:
        for v in ["false", "init", "full", "allinit", "allfull", "mininit", "minfull"]:
            add(base, f"uniquename-{v}", f"uniquename={v}", "uniquename", f"uniquename={v}")
    for base in BASES:
        for v in ["true", "false", "minyear"]:
            add(base, f"uniquelist-{v}", f"uniquelist={v}", "uniquelist", f"uniquelist={v}")
        for slug, opts in [("maxnames-1", "maxnames=1"), ("maxnames-2-minnames-2", "maxnames=2,minnames=2"),
                           ("maxnames-99", "maxnames=99")]:
            add(base, slug, opts, "maxnames", opts)
        for slug, opts in [("maxbibnames-99-maxcitenames-1", "maxbibnames=99,maxcitenames=1"),
                           ("maxbibnames-1-maxcitenames-99", "maxbibnames=1,maxcitenames=99")]:
            add(base, slug, opts, "maxbibnames", opts)
        # the non-default value of labeldateparts for this base
        v = "false" if base == "authoryear" else "true"
        add(base, f"labeldateparts-{v}", f"labeldateparts={v}", "labeldateparts", f"labeldateparts={v}")
        add(base, "sortcase-false", "sortcase=false", "sortcase", "sortcase=false")
        add(base, "sortupper-false", "sortupper=false", "sortupper", "sortupper=false")
        add(base, "useprefix-true", "useprefix=true", "useprefix", "useprefix=true")
        add(base, "giveninits-true", "giveninits=true", "giveninits", "giveninits=true")
    for base, sortings in [("authoryear", ["nty", "nyt", "nyvt", "anyt", "anyvt", "ynt", "ydnt", "none", "debug"]),
                           ("numeric", ["nty", "nyt", "nyvt", "anyt", "anyvt", "ynt", "ydnt", "none", "debug"]),
                           ("alphabetic", ["nty", "ynt", "none"])]:
        for v in sortings:
            add(base, f"sorting-{v}", f"sorting={v}", "sorting", f"sorting={v}")
    for slug, (desc, pre) in SOURCEMAPS.items():
        add("authoryear", slug, "", "sourcemap", f"\\DeclareSourcemap: {desc}", preamble=pre)
    for loc in ["en_US", "de_DE", "sv_SE", "fr_FR", "es_ES", "ru_RU", "da_DK", "cs_CZ",
                "pl_PL", "nb_NO"]:
        add("authoryear", f"sortlocale-{loc}", f"sortlocale={loc}", "sortlocale", f"sortlocale={loc}")
    # CJK sort locale: the PAR binary (O1) dies (BB-011); O3 works and bibers
    # supports it (DC-009). The golden records O1's crash.
    add("authoryear", "sortlocale-ja_JP", "sortlocale=ja_JP", "sortlocale",
        "sortlocale=ja_JP (O1 dies: BB-011; O3 differs)", tags=["bug:BB-011", "o3-differs"],
        allow=["DC-009"])
    return out


def styles() -> list[Spec]:
    out = []
    for st in STANDARD:
        out.append(Spec(name=st, style=st, tags=["suite:styles", "standard", f"style:{st}"],
                        description=f"\\nocite{{*}} over biblatex-examples.bib, standard style {st}"))
    for st, kw in CONTRIB.items():
        out.append(Spec(name=st, style=st, tags=["suite:styles", "contributed", f"style:{st}"],
                        description=f"\\nocite{{*}} over biblatex-examples.bib, contributed style {st}",
                        **kw))
    return out


def build(s: Spec) -> str:
    tex = tex_for(s)
    stem = s.name
    with tempfile.TemporaryDirectory(prefix="bibers-st-") as td:
        work = Path(td)
        (work / f"{stem}.tex").write_text(tex, encoding="utf-8")
        r = run_latex(work, f"{stem}.tex", s.engine)
        bcf = work / f"{stem}.bcf"
        if not bcf.exists():
            return f"FAILED ({s.engine}): {latex_error(work, stem)}"
        if r.returncode != 0:
            return f"FAILED ({s.engine}, exit {r.returncode}): {latex_error(work, stem)}"
        files = {f"{stem}.tex": tex, f"{stem}.bcf": bcf.read_bytes()}
        # Styles may add their own data files (archaeologie): copy them in.
        for _, _, p in bcf_datasources(bcf):
            if p == "biblatex-examples.bib":
                continue
            found = subprocess.run(["kpsewhich", p], capture_output=True, text=True).stdout.strip()
            if "/" in p or not found:
                return f"FAILED: data source {p} not found"
            files[p] = Path(found)
        spec = dict(
            description=s.description,
            source="generated by tools/corpus/gen_styles.py (pdflatex -draftmode)",
            args=["--noconf", f"{stem}.bcf"],
            outputs=[f"{stem}.bbl"],
            shared=["biblatex-examples.bib"],
            tags=s.tags,
            allow=s.allow,
        )
        write_case(SUITE / stem, spec, files)
        return "ok"


def main() -> None:
    args = sys.argv[1:]
    listing = "--list" in args
    args = [a for a in args if a != "--list"]
    pat = re.compile(args[0] if args else ".")
    specs = [s for s in styles() + matrix() if pat.search(s.name)]
    if listing:
        for s in specs:
            print(s.name, " ".join(s.tags))
        log(f"{len(specs)} cases")
        return
    ensure_shared_examples_bib()
    if not args and SUITE.exists():  # full run: drop cases that are no longer generated
        names = {s.name for s in specs}
        for d in SUITE.iterdir():
            if d.is_dir() and d.name not in names:
                log(f"removing stale case {d.name}")
                shutil.rmtree(d)
    failed = {}
    with cf.ThreadPoolExecutor(max_workers=8) as ex:
        for s, res in zip(specs, ex.map(build, specs)):
            log(f"{s.name:45} {res}")
            if res != "ok":
                failed[s.name] = res
                if (SUITE / s.name).exists():
                    shutil.rmtree(SUITE / s.name)
    log(f"styles: {len(specs) - len(failed)} written, {len(failed)} failed")


if __name__ == "__main__":
    main()
