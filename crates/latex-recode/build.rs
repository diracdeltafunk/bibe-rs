//! Turns the vendored `data/recode_data.xml` (biber 2.22, Artistic-2.0) into
//! static Rust tables, using the same reader as runtime `--recodedata` files.

#[path = "src/xmldata.rs"]
#[allow(dead_code)]
mod xmldata;

use std::fmt::Write as _;

fn main() {
    let src = "data/recode_data.xml";
    println!("cargo::rerun-if-changed={src}");
    println!("cargo::rerun-if-changed=src/xmldata.rs");
    let xml = std::fs::read_to_string(src).expect("read recode_data.xml");
    let data = xmldata::parse(&xml).expect("parse recode_data.xml");

    let mut out = String::new();
    out.push_str("// @generated by build.rs from data/recode_data.xml\n");
    out.push_str("pub(crate) static BUILTIN: StaticData = StaticData {\n    blocks: &[\n");
    for b in &data.blocks {
        writeln!(
            out,
            "        StaticMaps {{ ty: {:?}, sets: &{:?}, maps: &[",
            b.ty, b.sets
        )
        .unwrap();
        for m in &b.maps {
            writeln!(
                out,
                "            ({:?}, {:?}, {}, {}),",
                m.from, m.to, m.preferred, m.raw
            )
            .unwrap();
        }
        out.push_str("        ] },\n");
    }
    writeln!(
        out,
        "    ],\n    decode_exclude: &{:?},\n    encode_exclude: &{:?},\n}};",
        data.decode_exclude, data.encode_exclude
    )
    .unwrap();
    let dest = std::path::Path::new(&std::env::var("OUT_DIR").unwrap()).join("builtin_data.rs");
    std::fs::write(dest, out).unwrap();
}
