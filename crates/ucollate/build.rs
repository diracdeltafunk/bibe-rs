//! Compiles `data/allkeys-13.0.0.txt` (DUCET 13.0.0) into static lookup tables.
//!
//! Output (`$OUT_DIR/ducet.rs`):
//! * `DUCET_STAGE1: [u16; 0x2200]` – block number for each 128-code-point block;
//! * `DUCET_STAGE2: [u32; _]` – per code point: `0` (no entry), or
//!   `PRESENT | maxlen << 28 | len << 20 | start` (see `src/tables.rs`);
//! * `DUCET_CES: [Ce; _]` – the collation element pool;
//! * `DUCET_CONTR_KEYS: [u64; _]` / `DUCET_CONTR_VALS: [u32; _]` – sorted contractions.

use std::collections::BTreeMap;
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

const BLOCK: usize = 128;
const NBLOCKS: usize = 0x110000 / BLOCK;

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let src = manifest.join("data/allkeys-13.0.0.txt");
    println!("cargo:rerun-if-changed=data/allkeys-13.0.0.txt");
    println!("cargo:rerun-if-changed=build.rs");
    let text = fs::read_to_string(&src).expect("read allkeys");

    // (cps) -> CEs; CE = (var, p, s, t)
    let mut singles: BTreeMap<u32, Vec<(bool, u16, u16, u16)>> = BTreeMap::new();
    let mut contractions: BTreeMap<Vec<u32>, Vec<(bool, u16, u16, u16)>> = BTreeMap::new();
    let mut version = None;
    for raw in text.lines() {
        let line = raw.trim_end_matches('\r');
        if let Some(v) = line.strip_prefix("@version ") {
            version = Some(v.trim().to_string());
            continue;
        }
        let line = line.split('#').next().unwrap().trim();
        if line.is_empty() || line.starts_with('@') {
            continue;
        }
        let (k, v) = line.split_once(';').expect("missing ';'");
        let cps: Vec<u32> = k
            .split_whitespace()
            .map(|h| u32::from_str_radix(h, 16).expect("bad code point"))
            .collect();
        let mut ces = Vec::new();
        for elt in v.split(']') {
            let elt = elt.trim();
            if elt.is_empty() {
                continue;
            }
            let elt = elt.strip_prefix('[').expect("CE must start with [");
            let var = match &elt[..1] {
                "*" => true,
                "." => false,
                _ => panic!("bad CE {elt}"),
            };
            let w: Vec<u16> = elt[1..]
                .split('.')
                .map(|h| u16::from_str_radix(h, 16).expect("bad weight"))
                .collect();
            assert_eq!(w.len(), 3, "DUCET 13 has three weights per element");
            ces.push((var, w[0], w[1], w[2]));
        }
        assert!(!cps.is_empty() && cps.len() <= 3);
        if cps.len() == 1 {
            assert!(singles.insert(cps[0], ces).is_none(), "duplicate");
        } else {
            assert!(contractions.insert(cps, ces).is_none(), "duplicate");
        }
    }
    assert_eq!(version.as_deref(), Some("13.0.0"));

    let mut pool: Vec<(bool, u16, u16, u16)> = Vec::new();
    let mut intern = |ces: &[(bool, u16, u16, u16)]| -> u32 {
        let start = pool.len() as u32;
        pool.extend_from_slice(ces);
        assert!(ces.len() < 256 && start < (1 << 20));
        start | (ces.len() as u32) << 20
    };

    let mut maxlen: BTreeMap<u32, u32> = BTreeMap::new();
    for k in contractions.keys() {
        let e = maxlen.entry(k[0]).or_insert(1);
        *e = (*e).max(k.len() as u32);
    }
    let mut stage2_full = vec![0u32; 0x110000];
    for (&cp, ces) in &singles {
        stage2_full[cp as usize] = 0x8000_0000 | intern(ces);
    }
    for (&cp, &ml) in &maxlen {
        assert!(ml < 8);
        stage2_full[cp as usize] |= ml << 28;
    }
    let mut contr_keys = Vec::new();
    let mut contr_vals = Vec::new();
    for (k, ces) in &contractions {
        let mut key = 0u64;
        for &cp in k {
            key = key << 21 | (cp as u64 + 1);
        }
        key <<= 21 * (3 - k.len() as u32);
        contr_keys.push(key);
        contr_vals.push(intern(ces));
    }
    let mut order: Vec<usize> = (0..contr_keys.len()).collect();
    order.sort_by_key(|&i| contr_keys[i]);

    // two-stage table with block deduplication
    let mut blocks: Vec<&[u32]> = Vec::new();
    let mut block_index: BTreeMap<&[u32], u16> = BTreeMap::new();
    let mut stage1 = Vec::with_capacity(NBLOCKS);
    for b in 0..NBLOCKS {
        let blk = &stage2_full[b * BLOCK..(b + 1) * BLOCK];
        let idx = *block_index.entry(blk).or_insert_with(|| {
            blocks.push(blk);
            (blocks.len() - 1) as u16
        });
        stage1.push(idx);
    }

    let mut out = String::new();
    writeln!(out, "// @generated by build.rs from data/allkeys-13.0.0.txt").unwrap();
    writeln!(out, "pub(crate) static DUCET_STAGE1: [u16; {NBLOCKS}] = [").unwrap();
    for chunk in stage1.chunks(32) {
        let s: Vec<String> = chunk.iter().map(|v| v.to_string()).collect();
        writeln!(out, "{},", s.join(",")).unwrap();
    }
    writeln!(out, "];").unwrap();
    writeln!(
        out,
        "pub(crate) static DUCET_STAGE2: [u32; {}] = [",
        blocks.len() * BLOCK
    )
    .unwrap();
    for blk in &blocks {
        let s: Vec<String> = blk.iter().map(|v| format!("{v:#x}")).collect();
        writeln!(out, "{},", s.join(",")).unwrap();
    }
    writeln!(out, "];").unwrap();
    writeln!(out, "pub(crate) static DUCET_CES: [Ce; {}] = [", pool.len()).unwrap();
    for &(v, p, s, t) in &pool {
        writeln!(out, "Ce::new({p:#x},{s:#x},{t:#x},0,{v}),").unwrap();
    }
    writeln!(out, "];").unwrap();
    writeln!(
        out,
        "pub(crate) static DUCET_CONTR_KEYS: [u64; {}] = [",
        order.len()
    )
    .unwrap();
    for &i in &order {
        writeln!(out, "{:#x},", contr_keys[i]).unwrap();
    }
    writeln!(out, "];").unwrap();
    writeln!(
        out,
        "pub(crate) static DUCET_CONTR_VALS: [u32; {}] = [",
        order.len()
    )
    .unwrap();
    for &i in &order {
        writeln!(out, "{:#x},", contr_vals[i]).unwrap();
    }
    writeln!(out, "];").unwrap();

    let dest = PathBuf::from(env::var("OUT_DIR").unwrap()).join("ducet.rs");
    fs::write(dest, out).unwrap();
}
