//! The biblatexml writer (`bibers_core::output::biblatexml`, tool mode;
//! end to end in the `bltxml/tool-*` and `ported/tool-bltxml-*` corpus
//! cases), exercised directly on the state `fetch_data` builds from a
//! document-mode biblatexml case: well-formed and deterministic output.

use bibers::run::{SetupResult, setup};
use bibers_core::env::Env;
use bibers_core::output::biblatexml::{BltxmlWriter, schema_file_for_dsn};
use bibers_core::pipeline::{Ctx, fetch};

fn corpus(p: &str) -> std::path::PathBuf {
    std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../tests/corpus")
        .join(p)
}

/// Write the entries `fetch_data` reads from `case` as biblatexml.
fn write_case(case: &str, bcf: &str) -> String {
    let work = tempfile::tempdir().unwrap();
    for e in std::fs::read_dir(corpus(case)).unwrap().flatten() {
        if e.path().is_file() {
            std::fs::copy(e.path(), work.path().join(e.file_name())).unwrap();
        }
    }
    let env = Env::isolated(work.path());
    let args: Vec<String> = ["-q", "-q", "--noconf", bcf]
        .iter()
        .map(|s| s.to_string())
        .collect();
    let SetupResult::Ready(s) = setup(&args, &env) else {
        panic!("setup failed")
    };
    let bibers::run::Setup {
        mut cfg,
        doc,
        mut log,
        ..
    } = *s;
    let dm = cfg.dm.take().unwrap();
    let mut ctx = Ctx {
        cfg: &mut cfg,
        dm: &dm,
        doc: &doc,
        log: &mut log,
        env: &env,
        run: Default::default(),
    };
    let mut st = fetch::init_section(&mut ctx, "0").unwrap();
    fetch::fetch_data(&mut ctx, &mut st).unwrap();
    let mut w = BltxmlWriter::new(&ctx, &schema_file_for_dsn("test.bltxml"));
    let missing = w.section(&ctx, &st);
    assert!(missing.is_empty(), "{missing:?}");
    w.finish()
}

#[test]
fn writes_fields_names_dates() {
    let out = write_case("bltxml/fields-allkeys", "doc.bcf");
    assert!(out.starts_with(
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<?xml-model href=\"test.rng\" type=\"application/xml\" schematypens=\"http://relaxng.org/ns/structure/1.0\"?>\n<!-- Auto-generated by Biber::Output::biblatexml -->\n\n<bltx:entries xmlns:bltx=\"http://biblatex-biber.sourceforge.net/biblatexml\">\n  <bltx:entry id=\"f1\" entrytype=\"article\">\n"
    ), "{out}");
    // aliases, options, names, lists, ranges, dates, annotations
    for want in [
        "    <bltx:ids>\n      <bltx:list>\n        <bltx:item>f1alias</bltx:item>\n        <bltx:item>f1alias2</bltx:item>\n      </bltx:list>\n    </bltx:ids>\n",
        "    <bltx:options>skipbiblist=1,useprefix=1</bltx:options>\n",
        "    <bltx:names type=\"author\">\n      <bltx:name>\n        <bltx:namepart type=\"family\" initial=\"D\">Doe</bltx:namepart>\n        <bltx:namepart type=\"given\" initial=\"J\">John</bltx:namepart>\n      </bltx:name>\n    </bltx:names>\n",
        "    <bltx:language>\n      <bltx:list>\n        <bltx:item>english</bltx:item>\n        <bltx:item>german</bltx:item>\n      </bltx:list>\n    </bltx:language>\n",
        "    <bltx:pages>\n      <bltx:list>\n        <bltx:item>\n          <bltx:start>1</bltx:start>\n          <bltx:end>10</bltx:end>\n        </bltx:item>\n",
        "    <bltx:date>2001-02-03</bltx:date>\n",
        "    <bltx:annotation field=\"title\" name=\"default\" literal=\"0\">t-ann</bltx:annotation>\n",
        "    <bltx:annotation field=\"language\" name=\"alt\" item=\"2\" literal=\"1\">lang2</bltx:annotation>\n",
        "    <bltx:annotation field=\"author\" name=\"default\" item=\"1\" part=\"family\" literal=\"0\">fam</bltx:annotation>\n",
        "    <bltx:title>A &amp; B &lt;c&gt; title with é and é</bltx:title>\n",
    ] {
        assert!(out.contains(want), "missing {want:?} in\n{out}");
    }
    assert!(out.ends_with("  </bltx:entry>\n</bltx:entries>\n"));
    // well-formed, and deterministic
    bibers_core::xmldom::Dom::parse(&out).unwrap();
    assert_eq!(out, write_case("bltxml/fields-allkeys", "doc.bcf"));
}

#[test]
fn writes_dates() {
    let out = write_case("bltxml/dates", "doc.bcf");
    bibers_core::xmldom::Dom::parse(&out).unwrap();
    for want in [
        "<bltx:date>2001-02-03T10:20:30+05:30</bltx:date>",
        "<bltx:date>199X</bltx:date>",
        // biber's `sprintf('%.2d', 'XX')`: 1999-XX is written as 1999-00
        "<bltx:date>1999-00</bltx:date>",
        "<bltx:date>2001~</bltx:date>",
        "<bltx:date>2001%</bltx:date>",
        "<bltx:date>2001-21</bltx:date>",
        "<bltx:start>2001</bltx:start>\n      <bltx:end>2003</bltx:end>",
        "<bltx:date type=\"orig\">1850</bltx:date>",
    ] {
        assert!(out.contains(want), "missing {want:?} in\n{out}");
    }
}

/// Manual check: `BLTXML_CASE=bltxml/dates BLTXML_OUT=/tmp/x.bltxml cargo
/// test -p bibers --test bltxml_output -- --ignored` writes a case's output
/// (to diff with biber's tool mode on the same .bltxml).
#[test]
#[ignore]
fn write_case_to_file() {
    let case = std::env::var("BLTXML_CASE").unwrap_or_else(|_| "bltxml/fields-allkeys".into());
    let out = std::env::var("BLTXML_OUT").expect("BLTXML_OUT");
    std::fs::write(out, write_case(&case, "doc.bcf")).unwrap();
}
