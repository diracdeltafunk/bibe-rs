//! RELAX NG validation of biber's XML inputs (`--validate-control`,
//! `--validate-config`, `--validate-bltxml`; docs/compat.md DC-033), a port
//! of `Biber::Utils::validate_biber_xml` (Utils.pm:1193) on the `relaxng`
//! crate.
//!
//! biber validates with libxml2 and reports only the verdict:
//! `'FILE' validates against schema 'SCHEMA'` (INFO) or `'FILE' failed to
//! validate against schema 'SCHEMA'` (ERROR). libxml2's own messages appear
//! only in `--debug` output (as a Perl dump of the error object); bibers
//! logs its own messages there, one DEBUG line per validity error in
//! xmllint's format.
//!
//! The `.bcf` and config schemas are compiled in (`data/schemata`). biber
//! names its installed copies (`…/Biber/bcf.rng`); bibers names them
//! [`BUILTIN_SCHEMA_DIR`]`/bcf.rng`.

use std::sync::OnceLock;

use relaxng::{Options, Schema, ValidateError};

use crate::env::Env;
use crate::log::{Fatal, Logger};
use crate::quirks::{Quirk, Quirks};
use crate::{biber_error, debug, info};

/// The pseudo-directory bibers names its built-in schemas with.
pub const BUILTIN_SCHEMA_DIR: &str = "(built-in)";

const BCF_RNG: &str = include_str!("../../../data/schemata/bcf.rng");
const CONFIG_RNG: &str = include_str!("../../../data/schemata/config.rng");

/// Which schema to validate against.
#[derive(Clone, Copy, Debug)]
pub enum SchemaKind<'a> {
    /// The `.bcf` schema (`bcf.rng`).
    Control,
    /// The biber config file schema (`config.rng`).
    Config,
    /// A biblatexml schema generated by bibers (`generate_bltxml_schema`),
    /// read from this path.
    Bltxml(&'a str),
}

fn builtin(kind: SchemaKind<'_>) -> &'static Schema {
    static BCF: OnceLock<Schema> = OnceLock::new();
    static CONFIG: OnceLock<Schema> = OnceLock::new();
    let (cell, text) = match kind {
        SchemaKind::Config => (&CONFIG, CONFIG_RNG),
        _ => (&BCF, BCF_RNG),
    };
    cell.get_or_init(|| Schema::parse(text).expect("the built-in schemas are correct"))
}

/// Perl's `$!` text for an I/O error (Rust appends ` (os error N)`).
fn errno_text(e: &std::io::Error) -> String {
    let s = e.to_string();
    match s.rfind(" (os error ") {
        Some(i) => s[..i].to_string(),
        None => s,
    }
}

/// Read an XML file as text: UTF-8, or else bytes as Latin-1.
fn read_xml(env: &Env, file: &str) -> std::io::Result<String> {
    let bytes = std::fs::read(env.resolve(file))?;
    Ok(match String::from_utf8(bytes) {
        Ok(s) => s,
        Err(e) => e.into_bytes().iter().map(|&b| b as char).collect(),
    })
}

/// Validate `file` against a schema, logging biber's messages. Returns
/// `Err(Fatal)` when the (fatal) error should stop the run.
pub fn validate_biber_xml(
    log: &mut Logger,
    env: &Env,
    file: &str,
    kind: SchemaKind<'_>,
    quirks: Quirks,
) -> Result<(), Fatal> {
    let opts = Options {
        libxml2_interleave: quirks.on(Quirk::Libxml2Interleave),
    };
    let generated;
    let (schema, schema_name): (&Schema, String) = match kind {
        SchemaKind::Control => (builtin(kind), format!("{BUILTIN_SCHEMA_DIR}/bcf.rng")),
        SchemaKind::Config => (builtin(kind), format!("{BUILTIN_SCHEMA_DIR}/config.rng")),
        SchemaKind::Bltxml(path) => {
            let text = match std::fs::read_to_string(env.resolve(path)) {
                Ok(t) => t,
                Err(e) => {
                    log.biber_warn(format!(
                        "Cannot find XML::LibXML::RelaxNG schema '{path}'. Skipping validation : {}",
                        errno_text(&e)
                    ));
                    return Ok(());
                }
            };
            generated = match Schema::parse(&text) {
                Ok(s) => s,
                Err(e) => {
                    biber_error!(log, "'{path}' is not a valid RELAX NG schema: {e}")?;
                    return Ok(());
                }
            };
            (&generated, path.to_string())
        }
    };
    let text = match read_xml(env, file) {
        Ok(t) => t,
        Err(e) => {
            biber_error!(log, "Cannot read '{file}': {e}")?;
            return Ok(());
        }
    };
    match schema.validate_str_with(&text, &opts) {
        Ok(()) => {
            info!(log, "'{file}' validates against schema '{schema_name}'");
            Ok(())
        }
        Err(ValidateError::Invalid(errs)) => {
            for e in &errs {
                debug!(log, "{}", e.display_in(file));
            }
            biber_error!(log, "'{file}' failed to validate against schema '{schema_name}'")
        }
        Err(ValidateError::NotWellFormed(e)) => {
            // biber dies in XML::LibXML's parser here (a Perl error); the
            // .bcf and config file are already known to be well-formed.
            biber_error!(log, "'{file}' failed to validate against schema '{schema_name}'\n{file}: {e}")
        }
    }
}

