//! Compiles the vendored ISBN range file (`data/isbn/RangeMessage.xml`, see
//! `data/isbn/README.md`) into static tables, so bibers needs neither the file
//! nor network access at run time.

use std::fmt::Write as _;
use std::path::PathBuf;

#[path = "src/isbn_ranges.rs"]
#[allow(dead_code)]
mod isbn_ranges;

fn main() {
    let manifest = PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").expect("manifest dir"));
    let xml = manifest.join("../../data/isbn/RangeMessage.xml");
    println!("cargo:rerun-if-changed={}", xml.display());
    println!("cargo:rerun-if-changed=src/isbn_ranges.rs");
    let data = std::fs::read_to_string(&xml).expect("read data/isbn/RangeMessage.xml");
    let groups = isbn_ranges::parse_range_message(&data);
    assert!(
        groups.len() > 100,
        "RangeMessage.xml parse produced too few groups"
    );

    let mut out = String::new();
    let _ = writeln!(
        out,
        "// @generated by build.rs from data/isbn/RangeMessage.xml"
    );
    let _ = writeln!(
        out,
        "pub(crate) static GROUPS: &[(&str, &str, &str, &[(&str, &str)])] = &["
    );
    for g in &groups {
        let _ = write!(
            out,
            "    ({:?}, {:?}, {:?}, &[",
            g.ean_prefix, g.group, g.agency
        );
        for (lo, hi) in &g.ranges {
            let _ = write!(out, "({lo:?}, {hi:?}), ");
        }
        let _ = writeln!(out, "]),");
    }
    let _ = writeln!(out, "];");
    let date = data
        .split("<MessageDate>")
        .nth(1)
        .and_then(|s| s.split("</MessageDate>").next())
        .unwrap_or("");
    let _ = writeln!(out, "pub(crate) static MESSAGE_DATE: &str = {date:?};");

    let dest = PathBuf::from(std::env::var_os("OUT_DIR").expect("out dir")).join("isbn_ranges.rs");
    std::fs::write(dest, out).expect("write isbn_ranges.rs");
}
